-- The schema as it was when the app moved from SQLite to PostgreSQL (see docs/postgres-migration.md).
-- Times are ISO text ("2026-10-29T14:05:00", local time) and JSON is text, as they were in SQLite: the code compares
-- and slices them as strings. Changing them to timestamptz / jsonb is a later migration.

-- What phone numbers are compared on: the last 8 digits (with or without +216), else all the digits.
-- Same as db.number_key() in Python; tests check they agree.
CREATE FUNCTION number_key(number text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT CASE WHEN length(d) >= 8 THEN right(d, 8) ELSE d END
    FROM (SELECT regexp_replace(coalesce(number, ''), '[^0-9]', '', 'g') AS d) AS digits
$$;

-- Whether a call involves a number in SKIP_NUMBERS. db.connect() puts their keys, comma-separated, in the
-- call_analyzer.skip_keys setting of the connection.
CREATE FUNCTION skip_listed(caller text, called text) RETURNS boolean
LANGUAGE sql STABLE PARALLEL SAFE AS $$
    SELECT coalesce(current_setting('call_analyzer.skip_keys', true), '') <> ''
       AND (number_key(caller) = ANY (string_to_array(current_setting('call_analyzer.skip_keys', true), ','))
            OR number_key(called) = ANY (string_to_array(current_setting('call_analyzer.skip_keys', true), ',')))
$$;

