-- Any change to a call row bumps updated_at, whoever writes it (pipeline, web UI, manual SQL).
CREATE FUNCTION calls_touch() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.updated_at IS NULL THEN
            NEW.updated_at := to_char(localtimestamp, 'YYYY-MM-DD"T"HH24:MI:SS');
        END IF;
    ELSIF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at := to_char(localtimestamp, 'YYYY-MM-DD"T"HH24:MI:SS');
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER calls_touch BEFORE INSERT OR UPDATE ON calls FOR EACH ROW EXECUTE FUNCTION calls_touch();

